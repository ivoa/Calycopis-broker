# Deploy three broker pods and a client pod on a shared Podman network.
#

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
DEMO_DIR="$(dirname "${SCRIPT_DIR}")"
BROKER_DIR="$(dirname "${DEMO_DIR}")"

NETWORK_NAME="calycopis-demo"
BROKER_IMAGE="calycopis/broker:latest"
POSTGRES_IMAGE="docker.io/library/postgres:latest"

BROKERS=("alpha" "beta" "gamma")

ENV_DIR="${DEMO_DIR}/run"
mkdir -p "${ENV_DIR}"

echo "=== Creating Podman network: ${NETWORK_NAME} ==="
podman network create "${NETWORK_NAME}" 2>/dev/null || echo "Network ${NETWORK_NAME} already exists"

for broker in "${BROKERS[@]}"
do
    POD_NAME="broker-${broker}"
    PG_NAME="postgres-${broker}"
    BR_NAME="broker-svc-${broker}"
    CONFIG_DIR="${ENV_DIR}/${broker}"
    mkdir -p "${CONFIG_DIR}"

    DB_USER="$(pwgen -s 16 1)"
    DB_PASS="$(pwgen -s 32 1)"
    ADMIN_USER="$(pwgen -s 16 1)"
    ADMIN_PASS="$(pwgen -s 32 1)"

    cat > "${CONFIG_DIR}/database.yaml" <<EOF
spring:
    datasource:
        url: jdbc:postgresql://localhost:5432/calycopis
        username: ${DB_USER}
        password: ${DB_PASS}
        driverClassName: org.postgresql.Driver
        initialize: true
EOF

    cat > "${CONFIG_DIR}/admin.yaml" <<EOF
calycopis:
    admin:
        username: ${ADMIN_USER}
        password: ${ADMIN_PASS}
EOF

    cp "${DEMO_DIR}/config/${POD_NAME}/platform.yaml" "${CONFIG_DIR}/platform.yaml"

    echo ""
    echo "=== Deploying ${POD_NAME} ==="

    podman pod create \
        --replace \
        --name "${POD_NAME}" \
        --network "${NETWORK_NAME}"

    podman run \
        --rm \
        --detach \
        --replace \
        --name "${PG_NAME}" \
        --pod "${POD_NAME}" \
        --expose 5432 \
        --env "POSTGRES_DB=calycopis" \
        --env "POSTGRES_USER=${DB_USER}" \
        --env "POSTGRES_PASSWORD=${DB_PASS}" \
        "${POSTGRES_IMAGE}"

    echo "  Waiting for PostgreSQL to start..."
    sleep 5

    podman run \
        --rm \
        --detach \
        --replace \
        --name "${BR_NAME}" \
        --pod "${POD_NAME}" \
        --volume "${CONFIG_DIR}:/etc/calycopis:z" \
        "${BROKER_IMAGE}"

    echo "  Broker ${broker}: admin=${ADMIN_USER}"
done

echo ""
echo "=== Creating client pod ==="
podman pod create \
    --replace \
    --name "demo-client" \
    --network "${NETWORK_NAME}"

echo ""
echo "=== Writing environment file ==="

cat > "${ENV_DIR}/demo-env.sh" <<ENVEOF
# Generated by deploy.sh at $(date -Iseconds)

BROKER_ALPHA_URL="http://broker-alpha:8082"
BROKER_BETA_URL="http://broker-beta:8082"
BROKER_GAMMA_URL="http://broker-gamma:8082"

ENVEOF

for broker in "${BROKERS[@]}"
do
    CONFIG_DIR="${ENV_DIR}/${broker}"
    ADMIN_USER="$(yq '.calycopis.admin.username' "${CONFIG_DIR}/admin.yaml")"
    ADMIN_PASS="$(yq '.calycopis.admin.password' "${CONFIG_DIR}/admin.yaml")"
    BROKER_VAR="$(echo "${broker}" | tr '[:lower:]' '[:upper:]')"
    cat >> "${ENV_DIR}/demo-env.sh" <<ENVEOF
BROKER_${BROKER_VAR}_ADMIN_USER="${ADMIN_USER}"
BROKER_${BROKER_VAR}_ADMIN_PASS="${ADMIN_PASS}"
ENVEOF
done

echo ""
echo "=== Waiting for brokers to become healthy ==="
for broker in "${BROKERS[@]}"
do
    BROKER_URL="http://broker-${broker}:8082"
    echo -n "  Waiting for broker-${broker}..."
    for i in $(seq 1 60)
    do
        if podman run --rm --network "${NETWORK_NAME}" \
            docker.io/curlimages/curl:latest \
            -sf "${BROKER_URL}/openapi" > /dev/null 2>&1
        then
            echo " ready"
            break
        fi
        if [ "${i}" -eq 60 ]; then
            echo " TIMEOUT (check logs: podman logs broker-svc-${broker})"
        fi
        sleep 2
    done
done

echo ""
echo "=== Deployment complete ==="
echo "Environment file: ${ENV_DIR}/demo-env.sh"
echo ""
echo "Brokers:"
for broker in "${BROKERS[@]}"
do
    echo "  broker-${broker}: http://broker-${broker}:8082"
done
