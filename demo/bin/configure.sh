# Seed a demo user account in each of the three brokers.
# Designed to be run from the demo-client pod (or any host on the
# calycopis-demo network).
#

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
DEMO_DIR="$(dirname "${SCRIPT_DIR}")"
ENV_DIR="${DEMO_DIR}/run"

NETWORK_NAME="calycopis-demo"

if [ ! -f "${ENV_DIR}/demo-env.sh" ]; then
    echo "ERROR: ${ENV_DIR}/demo-env.sh not found. Run deploy.sh first."
    exit 1
fi

source "${ENV_DIR}/demo-env.sh"

DEMO_USER="demo-user"
DEMO_PASS="$(pwgen -s 24 1)"

BROKERS=("alpha" "beta" "gamma")
BROKER_URLS=("${BROKER_ALPHA_URL}" "${BROKER_BETA_URL}" "${BROKER_GAMMA_URL}")

create_user() {
    local broker_name="$1"
    local broker_url="$2"
    local admin_user="$3"
    local admin_pass="$4"

    local auth
    auth="$(echo -n "${admin_user}:${admin_pass}" | base64)"

    echo -n "  Creating user '${DEMO_USER}' on broker-${broker_name}... "
    local response
    local http_code
    http_code=$(
        podman run \
            --rm \
            --network "${NETWORK_NAME}" \
            docker.io/curlimages/curl:latest \
                --silent \
                --output /dev/null \
                -w "%{http_code}" \
                -X POST \
                -H "Content-Type: application/json" \
                -H "Accept: application/json" \
                -H "Authorization: Basic ${auth}" \
                -d "{\"username\": \"${DEMO_USER}\", \"password\": \"${DEMO_PASS}\"}" \
                "${broker_url}/admin/identities"
        )

    if [ "${http_code}" = "200" ] || [ "${http_code}" = "201" ]; then
        echo "OK (${http_code})"
    elif [ "${http_code}" = "409" ]; then
        echo "already exists (409)"
    else
        echo "FAILED (HTTP ${http_code})"
    fi
}

echo "=== Seeding demo user accounts ==="
echo ""

for i in "${!BROKERS[@]}"
do
    broker="${BROKERS[$i]}"
    url="${BROKER_URLS[$i]}"

    ADMIN_USER_VAR="BROKER_$(echo "${broker}" | tr '[:lower:]' '[:upper:]')_ADMIN_USER"
    ADMIN_PASS_VAR="BROKER_$(echo "${broker}" | tr '[:lower:]' '[:upper:]')_ADMIN_PASS"

    create_user "${broker}" "${url}" "${!ADMIN_USER_VAR}" "${!ADMIN_PASS_VAR}"
done

echo ""
echo "=== Writing demo user credentials ==="

cat > "${ENV_DIR}/demo-user.env" <<EOF
# Demo user credentials - generated by configure.sh at $(date -Iseconds)
DEMO_USER=${DEMO_USER}
DEMO_PASS=${DEMO_PASS}
BROKER_ALPHA_URL=${BROKER_ALPHA_URL}
BROKER_BETA_URL=${BROKER_BETA_URL}
BROKER_GAMMA_URL=${BROKER_GAMMA_URL}
EOF

echo "  Written to: ${ENV_DIR}/demo-user.env"
echo ""
echo "=== Configuration complete ==="
echo "  Username: ${DEMO_USER}"
echo "  Password: ${DEMO_PASS}"
